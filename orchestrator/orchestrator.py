def run_budget_agent(project_data, project_id):
    findings = []
    budget = project_data.get("budget")
    if not budget:
        return findings

    use_mock = os.getenv("USE_MOCK_AGENT", "0") == "1"
    if use_mock:
        response = make_mock_budget_response(budget)
    else:
        prompt = f"Check budget: planned_spend={budget['planned_spend']}, actual_spend={budget['actual_spend']}, pct_time_elapsed={budget['pct_time_elapsed']}."
        from agents.budget_tracking import budget_agent
        response = budget_agent.invoke({"messages": [{"role": "user", "content": prompt}]})

    tool_outputs = {}
    for m in response["messages"]:
        if isinstance(m, ToolMessage):
            tool_outputs[m.name] = m.content

    result = tool_outputs.get("check_budget_status", "")
    if result.startswith("over_budget"):
        finding = "over_budget"
    elif result.startswith("at_risk"):
        finding = "at_risk"
    else:
        finding = "on_budget"

    alert = tool_outputs.get("check_threshold_alerts", "")
    alert_note = f" | {alert}" if alert.startswith(("ALERT", "WARNING")) else ""

    label = finding.replace("_", " ").upper()
    finding_record = {
        "agent": "budget_tracking",
        "member": "Overall Project",
        "finding": finding,
        "raw_tool_outputs": tool_outputs,
        "user_response": f"[{label}] Project spend: {result}{alert_note}"
    }
    store_finding(finding_record, project_id)
    findings.append(finding_record)
    return findings

def get_reassignment_suggestion(project_data, exclude_person=None, required_skill=None):
    """Ask the Task Allocation agent who should take over a task, excluding the overloaded person."""
    candidates = []
    for member in project_data.get("team", []):
        if member["name"] == exclude_person:
            continue
        pct = (member["logged_hrs_week"] / member["capacity_hrs_week"]) * 100
        candidates.append({
            "name": member["name"],
            "utilization_pct": round(pct),
            "skills": member.get("skills", [])
        })

    if not candidates:
        return "No alternative team member available"

    use_mock = os.getenv("USE_MOCK_AGENT", "0") == "1"
    if use_mock:
        response = make_mock_allocation_response(candidates, required_skill=required_skill)
    else:
        skill_note = f" The task requires the skill: {required_skill}." if required_skill else ""
        prompt = f"Candidates: {json_lib.dumps(candidates)}.{skill_note} Who should take this task?"
        from agents.task_allocation import allocation_agent
        response = allocation_agent.invoke({"messages": [{"role": "user", "content": prompt}]})

    for m in response["messages"]:
        if isinstance(m, ToolMessage) and m.name == "recommend_assignee":
            return m.content
    return "Could not determine a recommendation"


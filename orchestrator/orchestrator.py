def run_resource_agent(project_data, project_id):
    findings = []
    use_mock = os.getenv("USE_MOCK_AGENT", "0") == "1"
    for member in project_data.get("team", []):
        if use_mock:
            response = make_mock_resource_response(member)
        else:
            prompt = f"Check utilization for {member['name']}: logged {member['logged_hrs_week']} hrs, capacity {member['capacity_hrs_week']} hrs."
            from agents.resource_usage import resource_agent
            response = resource_agent.invoke({"messages": [{"role": "user", "content": prompt}]})

        tool_outputs = {}
        for m in response["messages"]:
            if isinstance(m, ToolMessage):
                tool_outputs[m.name] = m.content

        util_result = tool_outputs.get("calculate_utilization", "")
        if "severely_overloaded" in util_result:
            finding = "severely_overloaded"
        elif "overloaded" in util_result:
            finding = "overloaded"
        elif "near_capacity" in util_result:
            finding = "near_capacity"
        else:
            finding = "available"

        finding_record = {
            "agent": "resource_usage",
            "member": member["name"],
            "finding": finding,
            "raw_tool_outputs": tool_outputs,
            "user_response": f"{'⚠️' if finding == 'overloaded' else '✅'} {member['name']} is {finding} ({util_result})".replace("⚠️", "[OVERLOADED]").replace("✅", "[OK]")
        }
        store_finding(finding_record, project_id)
        findings.append(finding_record)
    return findings

